$vendorBase = dirname(__DIR__, 3);
$srcJson = $vendorBase . '/twbs/bootstrap-icons/font/bootstrap-icons.json';
$outDir = dirname(__DIR__) . DIRECTORY_SEPARATOR . 'src';
$outFileName = 'BaseBI.php';
$outFile = $outDir . DIRECTORY_SEPARATOR . $outFileName;

if (!is_file($srcJson)) {
    echo 'srcJson file not found';

    exit(1);
}

if (is_file($outFile)) {
    $confirm = readline('outfile ' . $outFile . ' exists, overwrite? [yes|NO]: ');
    if (!is_string($confirm) || 'yes' !== trim($confirm)) {
        echo 'OK, exit.' . PHP_EOL;
    }
}

$json = file_get_contents($srcJson);
$srcMap = json_decode($json, true);

print_r($srcMap);

if (!is_array($srcMap)) {
    echo 'something went wrong while reading json to array.';

    exit(1);
}

