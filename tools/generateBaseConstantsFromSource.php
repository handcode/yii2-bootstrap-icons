namespace handcode\bootstrapIcons;

/** 
 * This is the base class for BI icons with constants for all 
 * bootstrap icons listed in twbs/bootstrap-icons/font/bootstrap-icons.json
 */
abstract class BaseBI
{

    // autogenerated list of constant for each icon
    // prefixed with _ as constants in PHP must always begin with CHAR
EOT;
$cLines = [];
$constLineFormat = "    public const _%s = '%s';";
foreach (array_keys($srcMap) as $key) {
    $cName = strtoupper(str_replace('-', '_', $key));
    $cLines[$key] = sprintf($constLineFormat, $cName, $key);
}
ksort($cLines);
$contentParts[] = implode(PHP_EOL, $cLines);

$contentParts[] = <<<'EOT'

}
EOT;

file_put_contents($outFile, implode(PHP_EOL, $contentParts));
